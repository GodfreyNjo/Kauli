def valid(code: str | None) -> bool:
    return bool(code) and code in LANGS


def direction(code: str) -> str:
    return "rtl" if code in RTL else "ltr"


def translate(lang: str, key: str, **kw) -> str:
    """The text for `key` in `lang`, English if that language lacks it, the key itself if nothing has it."""
    text = CATALOG.get(lang, {}).get(key) or EN.get(key) or key
    if not kw:
        return text
    try:
        return text.format(**kw)
    except (KeyError, IndexError, ValueError):
        return EN.get(key, key).format(**kw)


_MONTHS_EN = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def format_ts(lang: str, dt) -> str:
    """A short date and time the way that language writes it. English keeps "Oct 28, 14:05"."""
    hm = f"{dt.hour:02d}:{dt.minute:02d}"
    if lang in ("zh", "ja"):
        return f"{dt.month}月{dt.day}日 {hm}"
    if lang == "ko":
        return f"{dt.month}월 {dt.day}일 {hm}"
    if lang == "de":
        return f"{dt.day}.{dt.month}. {hm}"
    if lang in ("es", "fr", "pt", "sw", "hi", "ar"):
        return f"{dt.day}/{dt.month} {hm}"
    return f"{_MONTHS_EN[dt.month - 1]} {dt.day:02d}, {hm}"
