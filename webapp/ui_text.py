"""The words of the screens a client lives in, in the ten languages Kauli's translated site speaks.

A client who arrived on the French site signs up in French, lands on a French dashboard and pays on a French page, and
the choice follows their account from then on. Every screen listed in webapp/templates that calls t("key") reads from
here. A key missing from a language falls back to English, and tests/test_ui_language.py fails if a language is missing
any key or breaks a placeholder, so a screen can never show a blank.

Placeholders: {n} a number, {amount} a price, {what} one of the what_* words. Numbers always follow a colon or sit before
the word, so no language needs plural forms.
"""
